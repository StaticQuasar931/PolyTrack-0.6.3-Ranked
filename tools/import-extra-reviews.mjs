import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {reviewTag} from '../extra-tracks/reviewed.mjs';

const PREFIX = '// Generated by tools/import-extra-reviews.mjs. Tuple: quality, difficulty, vote, addedTags?, removedTags?.\nexport default ';
const plain = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const hash = /^[a-f0-9]{64}$/;

export function validateDataset(dataset) {
  if (!plain(dataset) || dataset.schema !== 1 || !plain(dataset.reviewers)) throw new Error('Invalid reviewed-data schema');
  if (Object.keys(dataset).some(key => !['schema', 'reviewers'].includes(key))) throw new Error('Unexpected dataset field');
  for (const [reviewer, rows] of Object.entries(dataset.reviewers)) {
    if (!/^[a-z][a-z0-9-]{0,47}$/.test(reviewer) || !plain(rows)) throw new Error('Invalid reviewer key');
    for (const [id, row] of Object.entries(rows)) {
      if (!hash.test(id) || !Array.isArray(row) || ![3, 5].includes(row.length)) throw new Error('Invalid review tuple');
      for (const value of row.slice(0, 2)) if (!Number.isInteger(value) || value < 0 || value > 10) throw new Error('Ratings must be 1..10 or 0 for absent');
      if (![-1, 0, 1].includes(row[2])) throw new Error('Invalid vote');
      if (row.length === 5) for (const values of row.slice(3)) {
        if (!Array.isArray(values) || values.length > 64 || values.some(tag => !reviewTag(tag) || reviewTag(tag) !== tag)
          || new Set(values).size !== values.length) throw new Error('Invalid tag deltas');
      }
      if (row.length === 5 && row[3].some(tag => row[4].includes(tag))) throw new Error('Conflicting tag delta');
      if (row.slice(0, 3).every(value => value === 0) && (row.length === 3 || !row[3].length && !row[4].length)) throw new Error('Empty review tuple');
    }
  }
  return dataset;
}

export function importReviews({catalog, input, reviewer, existing = {schema: 1, reviewers: {}}}) {
  validateDataset(existing);
  if (!/^[a-z][a-z0-9-]{0,47}$/.test(reviewer || '')) throw new Error('Supply a stable anonymous reviewer key, such as reviewer-001');
  if (!Array.isArray(catalog) || !plain(input?.tracks)) throw new Error('Catalog and tracks object are required');
  const canonical = new Map();
  for (const entry of catalog) {
    if (!hash.test(entry.trackId) || canonical.has(entry.trackId)) throw new Error('Catalog has invalid or duplicate canonical track IDs');
    canonical.set(entry.trackId, entry);
  }
  const rows = {}, unknown = [];
  for (const [id, value] of Object.entries(input.tracks).sort(([a], [b]) => a.localeCompare(b))) {
    if (!hash.test(id)) throw new Error('Invalid input track ID');
    if (!canonical.has(id)) { unknown.push(id); continue; }
    if (!plain(value)) throw new Error(`Invalid review for ${id}`);
    const score = key => {
      const number = value[key] ?? 0;
      if (!Number.isInteger(number) || number < 0 || number > 10) throw new Error(`Invalid ${key} for ${id}`);
      return number;
    };
    const vote = value.vote ?? 0;
    if (![-1, 0, 1].includes(vote)) throw new Error(`Invalid vote for ${id}`);
    const delta = key => {
      const values = value[key] ?? [];
      if (!Array.isArray(values) || values.length > 64 || values.some(tag => !reviewTag(tag))) throw new Error(`Invalid ${key} for ${id}`);
      return [...new Set(values.map(reviewTag))].sort();
    };
    const added = delta('addedTags'), removed = delta('removedTags');
    if (added.some(tag => removed.includes(tag))) throw new Error(`Conflicting tag delta for ${id}`);
    const row = [score('rating'), score('difficultyRating'), vote];
    if (added.length || removed.length) row.push(added, removed);
    if (row.some((value, index) => index < 3 ? value !== 0 : value.length)) rows[id] = row;
  }
  const dataset = {schema: 1, reviewers: {...existing.reviewers, [reviewer]: rows}};
  // Older opinions on tracks removed from the catalog must not silently survive.
  const stale = [...new Set(Object.values(dataset.reviewers).flatMap(rows => Object.keys(rows)).filter(id => !canonical.has(id)))].sort();
  if (stale.length) throw new Error(`Existing reviews have unknown canonical IDs: ${stale.join(', ')}`);
  const missing = catalog.filter(entry => !rows[entry.trackId]).map(entry => ({trackId: entry.trackId, name: entry.name})).sort((a, b) => a.trackId.localeCompare(b.trackId));
  return {dataset: validateDataset(dataset), report: {catalogTracks: catalog.length, suppliedTracks: Object.keys(input.tracks).length,
    reviewedTracks: Object.keys(rows).length, unknown, missing}};
}

export function serializeReviews(dataset) {
  validateDataset(dataset);
  const reviewers = Object.fromEntries(Object.entries(dataset.reviewers).sort(([a], [b]) => a.localeCompare(b)).map(([key, rows]) =>
    [key, Object.fromEntries(Object.entries(rows).sort(([a], [b]) => a.localeCompare(b)).map(([id, row]) => [id, row.length === 5 ? [...row.slice(0, 3), [...row[3]].sort(), [...row[4]].sort()] : [...row]]))]));
  return PREFIX + JSON.stringify({schema: 1, reviewers}) + ';\n';
}

export function parseReviews(source) {
  source = source.replace(/\r\n?/g, '\n');
  if (!source.startsWith(PREFIX) || !source.endsWith(';\n')) throw new Error('Unexpected reviewed-data module');
  return validateDataset(JSON.parse(source.slice(PREFIX.length, -2)));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2), options = {};
  for (let i = 0; i < args.length; i += 2) {
    if (!['--input', '--reviewer', '--catalog', '--output'].includes(args[i]) || !args[i + 1]) throw new Error('Use --input FILE --reviewer KEY [--catalog FILE] [--output FILE]');
    options[args[i].slice(2)] = args[i + 1];
  }
  if (!options.input || !options.reviewer) throw new Error('--input and --reviewer are required');
  const catalogPath = options.catalog || new URL('../extra-tracks/catalog.json', import.meta.url);
  const output = options.output || new URL('../extra-tracks/reviewed-data.mjs', import.meta.url);
  let existing;
  try { existing = parseReviews(await readFile(output, 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const result = importReviews({catalog: JSON.parse(await readFile(catalogPath, 'utf8')), input: JSON.parse(await readFile(options.input, 'utf8')), reviewer: options.reviewer, existing});
  await writeFile(output, serializeReviews(result.dataset));
  console.log(JSON.stringify(result.report, null, 2));
}
