import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export async function buildNamePolicy({check = false} = {}) {
  const source = (await fs.readFile(path.join(root, 'workers/ranked/src/public-name-policy.js'), 'utf8')).replace(/\r\n?/g,'\n');
  if (/^\s*import\s/m.test(source)) throw Error('Browser policy must be self-contained');
  const digest = createHash('sha256').update(source).digest('hex');
  const code = source.replace(/^export (?=(?:function|const|let|class)\b)/gm, '');
  const output = `// Generated by tools/build-name-policy.mjs. Source SHA-256: ${digest}\n(function(){\n'use strict';\n${code}\nglobalThis.__polytrackNamePolicy=Object.freeze({moderatePublicName,normalizeNameForCheck,sanitizeDisplayName,safePublicName,generatePublicName,generateFallbackName,generatedNameAt,generatedNameStats,sourceSha256:'${digest}'});\n})();\n`;
  const target = path.join(root, 'public-name-policy.js');
  if (check) {
    if (await fs.readFile(target, 'utf8') !== output) throw Error('Browser name policy is stale; run tools/build-name-policy.mjs');
  } else await fs.writeFile(target, output);
  return {digest, target};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildNamePolicy({check: process.argv.includes('--check')})));
}
