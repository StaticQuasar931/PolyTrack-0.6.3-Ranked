export const EVENT_LAUNCH_ENGINE = '895eeacbdfdd5f68b9db92c502af620709539c5211782809f610c1a76e60785d';
export const EVENT_OWN_GHOST_ENGINE = '32bfe32b8680597d9f1322dbcbb19242be38bee9ab243a379f5e449c3f4030fd';
