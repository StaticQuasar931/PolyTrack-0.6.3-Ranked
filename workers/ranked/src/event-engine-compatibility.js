  VERIFIER_ENGINE_DIGEST === EVENT_OWN_GHOST_ENGINE && [PRE_EVENT_LAUNCH_ENGINE, EVENT_LAUNCH_ENGINE].includes(digest) ||
  VERIFIER_ENGINE_DIGEST === MIGRATION_063_ENGINE && [PRE_EVENT_LAUNCH_ENGINE, EVENT_LAUNCH_ENGINE, EVENT_OWN_GHOST_ENGINE].includes(digest);
